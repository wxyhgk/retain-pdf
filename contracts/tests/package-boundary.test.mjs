// `./create-job-fields` 是包里唯一一个导出**运行期值**的子路径：其余子路径的 dist/*.js
// 都是 `export {}`（类型在运行期不存在）。mock 层要模拟后端的 deny_unknown_fields，
// 需要的正是一份运行期能读的字段名白名单；以前那份是手抄在 frontend/web 里的。
// 它由 scripts/generate-types.mjs 从 create-job.v1.schema.json 生成，
// `npm run generate:check`（本 npm test 的第一步）保证它不落后于 schema。
test("create-job field lists are generated values, not hand-written ones", () => {
  assert.match(generatedCreateJobFields, /Generated by scripts\/generate-types\.mjs/);
  assert.match(
    generatedCreateJobFields,
    /export const CREATE_JOB_TOP_LEVEL_FIELDS: readonly string\[\] = \[/,
  );
  assert.match(
    generatedCreateJobFields,
    /export const CREATE_JOB_SECTION_FIELDS: Readonly<\n\s*Record<JobPayloadSection, readonly string\[\]>\n>/,
  );
  // 五个段一个都不能少：少一个，mock 就会对那一段完全放行。
  for (const section of ["source", "ocr", "translation", "render", "runtime"]) {
    assert.match(generatedCreateJobFields, new RegExp(`^  ${section}: \\[$`, "m"));
  }
});

test("package has no runtime dependencies", () => {
  assert.deepEqual(manifest.dependencies, {});
});

test("generated DTO entries expose the stable consumer type names", () => {
  for (const typeName of [
    "ArtifactDisplayItemView",
    "BookSummaryView",
    "JobDetailView",
    "JobFailureInfo",
    "JobListItemView",
    "JobListView",
    "JobRuntimeInfo",
    "NormalizationSummaryView",
    "OcrProviderDiagnostics",
    "PublicResolvedJobSpec",
  ]) {
    assert.match(generatedJobStatus, new RegExp(`export (?:interface|type) ${typeName}\\b`));
  }
  for (const typeName of [
    "CreateJobInput",
    "GlossaryEntryInput",
    "JobSourceInput",
    "OcrInput",
    "RenderInput",
    "RuntimeInput",
    "TranslationInput",
  ]) {
    assert.match(generatedCreateJob, new RegExp(`export (?:interface|type) ${typeName}\\b`));
  }
  for (const typeName of [
    "JobEventListView",
    "JobEventRecord",
    "ListJobEventsQuery",
  ]) {
    assert.match(generatedJobEvents, new RegExp(`export (?:interface|type) ${typeName}\\b`));
  }
  for (const typeName of ["LibraryDeleteQuery", "LibraryDeleteResultView"]) {
    assert.match(generatedLibraryBooks, new RegExp(`export (?:interface|type) ${typeName}\\b`));
  }
  // 任务列表的类型只从 job-status 导出（library-books 重复登记的 GET /jobs 2026-10-23 删了）。
  for (const typeName of ["JobFailureBriefView", "JobListItemView", "JobListView", "ListJobsQuery"]) {
    assert.match(generatedJobStatus, new RegExp(`export (?:interface|type) ${typeName}\\b`));
    assert.doesNotMatch(generatedLibraryBooks, new RegExp(`export (?:interface|type) ${typeName}\\b`));
  }
});

