import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const frontendRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(frontendRoot, "..", "..");
const desktopPackagePath = path.resolve(repoRoot, "frontend/desktop/package.json");
const outputPath = path.join(frontendRoot, "src/platform/generated/app-version.ts");

function repoFromHomepage(homepage = "") {
  const match = `${homepage || ""}`.match(/github\.com\/([^/]+\/[^/#?]+)/i);
  return match ? match[1].replace(/\.git$/i, "") : "wxyhgk/retain-pdf";
}

function normalizeGitVersion(value = "") {
  const text = `${value || ""}`.trim();
  if (!text) {
    return "";
  }
  const dirty = /-dirty$/i.test(text);
  const withoutDirty = text.replace(/-dirty$/i, "");
  const described = withoutDirty.match(/^v?(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)-(\d+)-g([0-9a-f]+)$/i);
  if (described) {
    const [, base, commits, sha] = described;
    return `${base}+${commits}.g${sha}${dirty ? ".dirty" : ""}`;
  }
  const exact = withoutDirty.match(/^v?(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)$/i);
  if (exact) {
    return `${exact[1]}${dirty ? "+dirty" : ""}`;
  }
  const prefix = withoutDirty.match(/^v?(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)/);
  return prefix ? prefix[1] : "";
}

function readGithubRefVersion() {
  const refName = `${process.env.GITHUB_REF_NAME || ""}`.trim();
  const refType = `${process.env.GITHUB_REF_TYPE || ""}`.trim();
  if (refType === "tag") {
    return normalizeGitVersion(refName);
  }
  return normalizeGitVersion(refName);
}

function readGitVersion() {
  try {
    const described = execFileSync("git", ["describe", "--tags", "--always", "--dirty"], {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    return normalizeGitVersion(described);
  } catch (_err) {
    return "";
  }
}

const desktopPackage = JSON.parse(fs.readFileSync(desktopPackagePath, "utf8"));
const appVersion = (process.env.RETAIN_PDF_VERSION || "").trim()
  || readGithubRefVersion()
  || readGitVersion()
  || "0.0.0+unknown";
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  [
    "// Generated by scripts/generate-app-version.mjs. Do not edit by hand.",
    `export const APP_VERSION = ${JSON.stringify(appVersion)};`,
    `export const GITHUB_REPO = ${JSON.stringify(repoFromHomepage(desktopPackage.homepage))};`,
    "",
  ].join("\n"),
);

console.log(`frontend app version generated: ${appVersion}`);
